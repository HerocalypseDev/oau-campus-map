"""Download road lines and building outlines for the OAU map from OpenStreetMap.

Run from the project folder:  python tools/fetch_osm.py
Writes data/roads.js (walking routes), data/buildings.js (coloured building shapes)
and data/campus.js (campus boundary). Download size is about 1-3 MB.
Run only some parts:  python tools/fetch_osm.py campus buildings
"""
import json
import os
import re
import sys
import urllib.parse
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SERVERS = [
    "https://maps.mail.ru/osm/tools/overpass/api/interpreter",
    "https://overpass-api.de/api/interpreter",
]
# south, west, north, east: OAU campus plus nearby off-campus hostels.
BBOX = "7.485,4.495,7.565,4.580"


def overpass(query):
    data = urllib.parse.urlencode({"data": query}).encode()
    last = None
    for url in SERVERS:
        try:
            req = urllib.request.Request(url, data=data, headers={"User-Agent": "OAUMap-student-project"})
            with urllib.request.urlopen(req, timeout=180) as r:
                body = r.read()
            print(f"  {len(body) / 1024:.0f} KB from {url}")
            return json.loads(body)
        except Exception as e:  # try the next server
            print(f"  failed {url}: {e}")
            last = e
    raise SystemExit(f"All servers failed: {last}")


def r6(v):
    return round(v, 6)


def roads():
    print("Roads...")
    q = f"""[out:json][timeout:150][bbox:{BBOX}];
way["highway"]["highway"!~"construction|proposed|abandoned|platform|raceway|corridor|elevator|bus_stop"]["area"!="yes"]["foot"!="no"];
out tags geom;"""
    out = []
    for el in overpass(q)["elements"]:
        g = el.get("geometry")
        if not g or len(g) < 2:
            continue
        t = el.get("tags", {})
        flat = []
        for p in g:
            flat += [r6(p["lat"]), r6(p["lon"])]
        out.append([t.get("name", ""), t["highway"], flat])
    print(f"  {len(out)} road pieces")
    return out


def buildings():
    src = open(os.path.join(ROOT, "places.js"), encoding="utf-8").read()
    ids = sorted({int(i) for group in re.findall(r"osm:\s*\[([^\]]*)\]", src) for i in re.findall(r"\d+", group)})
    print(f"Buildings... ({len(ids)} outlines)")
    if not ids:
        return {}
    q = f"[out:json][timeout:120];way(id:{','.join(map(str, ids))});out geom;"
    out = {}
    for el in overpass(q)["elements"]:
        g = el.get("geometry")
        if g:
            out[str(el["id"])] = [[r6(p["lat"]), r6(p["lon"])] for p in g]
    missing = [i for i in ids if str(i) not in out]
    if missing:
        print("  not found on OpenStreetMap:", missing)
    return out


def campus():
    print("Campus boundary...")
    q = "[out:json][timeout:60];way(1552256471);out geom;"
    els = overpass(q)["elements"]
    return [[r6(p["lat"]), r6(p["lon"])] for p in els[0]["geometry"]] if els else []


def write_js(name, var, value):
    os.makedirs(os.path.join(ROOT, "data"), exist_ok=True)
    path = os.path.join(ROOT, "data", name)
    with open(path, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/fetch_osm.py. Data © OpenStreetMap contributors, ODbL.\n")
        f.write(f"window.{var} = {json.dumps(value, separators=(',', ':'))};\n")
    print(f"  wrote {path} ({os.path.getsize(path) / 1024:.0f} KB)")


if __name__ == "__main__":
    parts = set(sys.argv[1:]) or {"roads", "buildings", "campus"}
    if "roads" in parts:
        write_js("roads.js", "ROADS", roads())
    if "buildings" in parts:
        write_js("buildings.js", "BUILDINGS", buildings())
    if "campus" in parts:
        write_js("campus.js", "CAMPUS", campus())
    sys.exit(0)
